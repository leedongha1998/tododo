--       delete-account:  탈퇴한 사람의 사진
--   - 같은 변경에서 submit-evidence가 (a) 사진이 실제로 있을 때만 접수하고(빈 경로로 시각을 먼저
--     잡아 두는 길) (b) 거부 시 지우는 대상을 **어떤 제출도 가리키지 않는 경로**로 한정한다
--     (그러지 않으면 판정 중에 내 제출 경로를 다시 보내 거부당하는 것만으로 서버가 대신 지워 준다).
--     그 둘은 코드 쪽이라 여기에는 없다.
drop policy if exists "participants can delete own evidence" on storage.objects;
