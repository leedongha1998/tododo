-- 무엇이 문제였나
--   "participants can delete own evidence"(20260918120000:70)는 내 폴더의 사진이면 대결 상태와
--   상관없이 언제든 지우게 했다. 업로드(insert) 정책은 판정 창이 열리기 전까지 열려 있고 update
--   정책은 없으므로, 이 둘이 합쳐져 두 가지 악용이 가능했다(앱이 아니라 내 JWT로 API를 직접
--   부르는 사람만 할 수 있다).
--   1. **제출 시각을 지킨 채 사진을 바꾼다.** 이미 제출한 경로의 사진을 지우고 같은 경로에 다른
--      사진을 올리면 제출 행(object_path·submitted_at)은 그대로라 속도전의 "교체하면 시각이
--      갱신된다"와 품질전의 "제출은 한 번뿐"이 깨지고, 새 사진은 촬영 시각 검사도 거치지 않는다.
--   2. **질 것 같으면 대결을 무효로 만든다.** 판정 창이 열린 뒤 내 사진을 지우면 AI 재판정이
--      사진을 내려받지 못하고, 4회 실패하면 void_battle이 대결 전체를 무효로 끝낸다 — 진 쪽은
--      -3을 피하고 상대의 승리는 사라진다.
--
-- 어떻게 막나
--   - 이 정책을 없앤다. 앱에서 이 정책을 쓰던 곳은 탈퇴 시 사진 정리 하나뿐이었고, 그 일은
--     Edge Function `delete-account`가 service 롤로 한다(Storage API로 지워야 실제 파일이
--     지워진다 — storage.objects 행을 SQL로 지우는 것은 protect_objects_delete 트리거가 막는다).
--   - update 정책은 원래 없으므로, 이제 한 번 올라간 경로의 사진은 사용자가 바꿀 수도 지울 수도
--     없다. 남은 삭제 경로는 전부 서버(service 롤)다:
